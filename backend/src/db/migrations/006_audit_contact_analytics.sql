-- =============================================================================
-- Audit log, contact messages, first-party analytics, signup attribution
-- =============================================================================
CREATE TABLE AUDIT_LOG (
    AUDIT_ID     VARCHAR2(36)  PRIMARY KEY,
    ACTOR_ID     VARCHAR2(36),
    ACTION       VARCHAR2(60)  NOT NULL,
    TARGET_TYPE  VARCHAR2(30),
    TARGET_ID    VARCHAR2(64),
    SEVERITY     VARCHAR2(10)  DEFAULT 'INFO' NOT NULL,
    IP_ADDRESS   VARCHAR2(64),
    USER_AGENT   VARCHAR2(300),
    DETAILS      CLOB,
    CREATED_AT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_AUDIT_SEV CHECK (SEVERITY IN ('INFO','WARN','ALERT'))
);
CREATE INDEX IDX_AUDIT_CREATED ON AUDIT_LOG(CREATED_AT);
CREATE INDEX IDX_AUDIT_ACTION ON AUDIT_LOG(ACTION, CREATED_AT);

CREATE TABLE CONTACT_MESSAGES (
    MESSAGE_ID   VARCHAR2(36)  PRIMARY KEY,
    USER_ID      VARCHAR2(36),
    NAME         VARCHAR2(100) NOT NULL,
    EMAIL        VARCHAR2(255) NOT NULL,
    TOPIC        VARCHAR2(30)  NOT NULL,
    MESSAGE      CLOB          NOT NULL,
    STATUS       VARCHAR2(10)  DEFAULT 'NEW' NOT NULL,
    CREATED_AT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_CONTACT_STATUS CHECK (STATUS IN ('NEW','READ','CLOSED'))
);
CREATE INDEX IDX_CONTACT_CREATED ON CONTACT_MESSAGES(STATUS, CREATED_AT);

-- Consent-gated, cookieless page/event analytics. No IPs or user agents stored.
CREATE TABLE ANALYTICS_EVENTS (
    EVENT_ID     VARCHAR2(36)  PRIMARY KEY,
    SESSION_ID   VARCHAR2(64)  NOT NULL,
    USER_ID      VARCHAR2(36),
    EVENT_NAME   VARCHAR2(60)  NOT NULL,
    PATH         VARCHAR2(200),
    UTM_SOURCE   VARCHAR2(100),
    UTM_MEDIUM   VARCHAR2(100),
    UTM_CAMPAIGN VARCHAR2(100),
    REFERRER     VARCHAR2(200),
    PROPS        VARCHAR2(1000),
    CREATED_AT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_ANALYTICS_CREATED ON ANALYTICS_EVENTS(CREATED_AT, EVENT_NAME);

